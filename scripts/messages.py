os.makedirs(root, exist_ok=True)
for idx, loc in enumerate(["en", "vi"]):
    with open(os.path.join(root, f"{loc}.json"), "w", encoding="utf-8") as f:
        json.dump(build(M, idx), f, ensure_ascii=False, indent=2)
        f.write("\n")
